import re

from odoo import fields, models
from odoo.tools.float_utils import float_round


class PosOrderReceipt(models.AbstractModel):
    _inherit = "pos.order.receipt"

    def _get_custom_order_sequence_name(self):
        """Return the pos.order sequence name (e.g. 'UMEKP-003623') or a formatted fallback.

        :return: Formatted invoice / sequence number string
        :rtype: str
        """
        self.ensure_one()
        raw_name = (self.name or "").strip()
        is_temp_id = bool(re.search(r"\d{5}-\d{3}-\d{4}", raw_name))
        if raw_name and raw_name != "/" and not is_temp_id:
            return raw_name
        config_name = self.config_id.name or "POS"
        seq_num = self.sequence_number or 1
        return f"{config_name}/{str(seq_num).zfill(4)}"

    def _get_custom_waiting_number(self, data):
        """Resolve the waiting number / table name displayed at the bottom of the receipt.

        :param dict data: Base receipt data dictionary
        :return: Waiting number or table label
        :rtype: str
        """
        self.ensure_one()
        extra_table = data.get("extra_data", {}).get("table_name")
        if extra_table:
            return str(extra_table)
        if self.table_id:
            t_name = getattr(self.table_id, "table_name", False)
            if t_name:
                return str(t_name)
            if self.table_id.table_number is not None:
                return str(self.table_id.table_number)
        if self.floating_order_name:
            return str(self.floating_order_name)
        if self.tracking_number:
            return str(self.tracking_number)
        return ""

    def _generate_custom_receipt_data(self, data):
        """Build the custom_receipt dictionary matching the YOU & ME COFFEE bilingual layout.

        :param dict data: Base receipt data generated by super().order_receipt_generate_data()
        :return: Dictionary of custom receipt values
        :rtype: dict
        """
        self.ensure_one()
        config = self.config_id
        company = self.company_id
        symbol = self.currency_id.symbol or "$"

        khr_rate = (
            config.khr_exchange_rate
            if config.khr_exchange_rate and config.khr_exchange_rate > 1.0
            else 4100.0
        )

        amount_total = self.amount_total or 0.0
        total_in_khr = int(float_round(amount_total * khr_rate, precision_rounding=100.0))
        discount = sum(
            line._get_discount_amount()
            for line in self.lines.filtered(lambda l: l.discount > 0)
        )
        subtotal = amount_total + discount

        discount_pct_label = ""
        if subtotal > 0 and discount > 0:
            pct = round((discount / subtotal) * 100, 2)
            pct_str = str(int(pct)) if float(pct).is_integer() else f"{pct:.2f}"
            discount_pct_label = f"({pct_str}%)"

        order_change = abs(self.amount_return or 0.0)
        change_in_khr = int(float_round(order_change * khr_rate, precision_rounding=100.0))

        receipt_tz = self._order_receipt_tz()
        dt_source = self.date_order or fields.Datetime.now()
        local_dt = fields.Datetime.context_timestamp(self.with_context(tz=receipt_tz), dt_source)
        formatted_date = local_dt.strftime("%d-%m-%Y %I:%M:%S %p")

        khmer_company_name = config.receipt_header_khmer_company_name or ""
        header_company_name = config.receipt_header_company_name or company.name or ""
        vat_tin = re.sub(
            r"^(លេខអតប|vat\s*tin|vat|tin)\s*:\s*",
            "",
            (config.receipt_vat_tin or company.vat or "").strip(),
            flags=re.IGNORECASE,
        ).strip()

        address = config.receipt_address
        if not address:
            address = getattr(company, "english_address", False) or ", ".join(
                p for p in [company.street, company.street2, company.city, company.zip] if p
            )

        phone = re.sub(
            r"^(tell|tel|phone|telephone)\s*:\s*",
            "",
            (config.receipt_phone or company.phone or "").strip(),
            flags=re.IGNORECASE,
        ).strip()

        footer_khmer_note = (
            config.receipt_footer_khmer_note
            if config.receipt_footer_khmer_note is not False
            else "សូមអញ្ជើញមកម្តងទៀត!"
        )
        footer_note = (
            config.receipt_footer_note
            if config.receipt_footer_note is not False
            else "Thank You so much for your support!"
        )
        inv_no = self._get_custom_order_sequence_name()
        customer_name = self.partner_id.name if self.partner_id else "General"
        cashier_name = data.get("extra_data", {}).get("cashier_name") or ""
        font_size = config.receipt_font_size or 15

        display_price_incl = config.iface_tax_included == "total"
        orderlines = []
        for idx, line in enumerate(self.lines, start=1):
            qty = line.qty
            formatted_qty = str(int(qty)) if float(qty).is_integer() else f"{qty:.2f}"
            price_val = line.price_subtotal_incl if display_price_incl else line.price_subtotal
            no_disc_unit = (
                line._get_price_no_discount(config) / qty
                if qty
                else line.price_unit
            )
            disc_val = line.discount or 0.0
            disc_str = f"{int(disc_val)}%" if float(disc_val).is_integer() else f"{disc_val:.1f}%"
            lot_names = [lot.lot_name for lot in line.pack_lot_ids if lot.lot_name]
            orderlines.append({
                "index": idx,
                "product_name": line.full_product_name or line.product_id.display_name or "",
                "discount_str": disc_str,
                "customer_note": line.customer_note or "",
                "pack_lot_lines": lot_names,
                "formatted_qty": formatted_qty,
                "formatted_unit_price": f"{symbol}{no_disc_unit:.2f}",
                "formatted_price": f"{symbol}{price_val:.2f}",
            })

        payment_lines = []
        for payment in self.payment_ids:
            amt = payment.amount_currency or payment.amount or 0.0
            pay_symbol = (payment.foreign_currency_id or self.currency_id).symbol or symbol
            payment_lines.append({
                "name": payment.payment_method_id.name or "Cash",
                "amount_formatted": f"{pay_symbol}{amt:.2f}",
                "ticket": payment.ticket or "",
            })
        if not payment_lines:
            payment_lines.append({
                "name": "Cash",
                "amount_formatted": f"{symbol}0.00",
                "ticket": "",
            })

        return {
            "khmer_company_name": khmer_company_name,
            "company_name": header_company_name,
            "vat_tin": vat_tin,
            "address": address or "",
            "phone": phone,
            "font_size": font_size,
            "date": formatted_date,
            "inv_no": inv_no,
            "cashier_name": cashier_name,
            "customer_name": customer_name,
            "orderlines": orderlines,
            "subtotal": f"{symbol}{subtotal:.2f}",
            "discount": f"{symbol}{discount:.2f}",
            "discount_pct_label": discount_pct_label,
            "grand_total_khr": f"{total_in_khr:,}៛",
            "grand_total_usd": f"{symbol}{amount_total:.2f}",
            "khr_rate": f"{khr_rate:,.2f}៛",
            "show_change": bool(order_change > 0),
            "change_usd_formatted": f"{symbol}{order_change:.2f}",
            "change_khr": f"{change_in_khr:,}៛",
            "payment_lines": payment_lines,
            "waiting_number": self._get_custom_waiting_number(data),
            "footer_khmer_note": footer_khmer_note or "",
            "footer_note": footer_note or "",
        }

    def order_receipt_generate_data(self, basic_receipt=False):
        """Extend Odoo 20 receipt data payload with custom_receipt values.

        :param bool basic_receipt: Whether generating a basic (gift) receipt
        :return: Receipt template context dictionary
        :rtype: dict
        """
        data = super().order_receipt_generate_data(basic_receipt)
        data.setdefault("extra_data", {})["custom_receipt"] = self._generate_custom_receipt_data(
            data
        )
        return data
